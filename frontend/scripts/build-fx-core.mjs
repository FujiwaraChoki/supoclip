#!/usr/bin/env node
// Bundles fx-core (frontend/src/lib/fx/core/index.ts) into backend/src/fx_runtime/fx-core.js for the deno host (P2).
// The output is committed; CI rebuilds it and fails on drift, so the build must be byte-for-byte deterministic:
// no minify, no legal comments, no sourcemap, no timestamps, and paths in the bundle are relative to frontend/.
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const frontendDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entry = resolve(frontendDir, "src/lib/fx/core/index.ts");
// `--out <path>` writes elsewhere (determinism checks); the default is the committed bundle.
const outArg = process.argv.indexOf("--out");
const outfile = outArg > 0 && process.argv[outArg + 1]
  ? resolve(process.cwd(), process.argv[outArg + 1])
  : resolve(frontendDir, "../backend/src/fx_runtime/fx-core.js");
const BANNER = "// GENERATED by frontend/scripts/build-fx-core.mjs. Do not edit.";

// fx-core must stay host-agnostic: it runs in Chrome and under deno, never with DOM, Node or React (also linted).
const forbidden = {
  name: "fx-core-host-agnostic",
  setup(b) {
    b.onResolve({ filter: /^(node:|fs$|path$|react($|\/)|react-dom($|\/)|next($|\/))/ }, (args) => ({
      errors: [{ text: `fx-core may not import "${args.path}" (from ${relative(frontendDir, args.importer)})` }],
    }));
  },
};

const result = await build({
  absWorkingDir: frontendDir,
  entryPoints: [entry],
  outfile,
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  minify: false,
  sourcemap: false,
  legalComments: "none",
  charset: "utf8",
  treeShaking: true,
  banner: { js: BANNER },
  logLevel: "warning",
  plugins: [forbidden],
  metafile: true,
});

if (result.errors.length) process.exit(1);
const bytes = readFileSync(outfile);
const inputs = Object.keys(result.metafile.inputs).length;
console.log(
  `fx-core: ${relative(process.cwd(), outfile)} ${bytes.length} bytes, ${inputs} modules, ` +
    `sha256 ${createHash("sha256").update(bytes).digest("hex").slice(0, 16)}`,
);
