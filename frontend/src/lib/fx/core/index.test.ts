// @vitest-environment node
// fx-core's boundary: the lint rule that keeps it host-agnostic, the public index (§4.3) and the deterministic
// esbuild bundle the deno host runs (backend/src/fx_runtime/fx-core.js).
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { ESLint } from "eslint";
import { afterAll, describe, expect, it } from "vitest";

const CORE = fileURLToPath(new URL(".", import.meta.url));
const FRONTEND = resolve(CORE, "../../../..");
// index.ts re-exports modules owned by WP3b; until they exist the index and the bundle cannot build (gate 1 merge).
const INDEX_DEPS = ["types", "rng", "warp", "duck", "mapping", "censor", "grades", "scene", "frame", "raster", "render", "host"];
const indexBuilds = INDEX_DEPS.every((m) => existsSync(join(CORE, `${m}.ts`)));

describe("fx-core lint boundary", () => {
  const eslint = new ESLint({ cwd: FRONTEND });
  const lint = async (code: string, rel: string) => {
    const [result] = await eslint.lintText(code, { filePath: join(FRONTEND, rel) });
    return result.messages.map((m) => m.ruleId);
  };

  it("fails on a planted window/document/fs/node:/react use inside core", async () => {
    const planted = [
      'import { readFileSync } from "fs";',
      'import { join } from "node:path";',
      'import { useState } from "react";',
      "export const leak = [window.devicePixelRatio, document.title, readFileSync, join, useState];",
    ].join("\n");
    const rules = await lint(planted, "src/lib/fx/core/overlays/__planted.ts");
    expect(rules.filter((r) => r === "no-restricted-globals")).toHaveLength(2);
    expect(rules.filter((r) => r === "no-restricted-imports")).toHaveLength(3);
  }, 60_000);

  it("leaves tests, test utils and code outside core alone", async () => {
    const code = 'import { readFileSync } from "node:fs";\nexport const x = [readFileSync, window.innerWidth];';
    expect(await lint(code, "src/lib/fx/core/__planted.test.ts")).not.toContain("no-restricted-imports");
    expect(await lint(code, "src/lib/fx/core/test-utils/__planted.ts")).not.toContain("no-restricted-globals");
    expect(await lint(code, "src/lib/fx/browser-host-planted.ts")).not.toContain("no-restricted-globals");
  }, 60_000);
});

describe.skipIf(!indexBuilds)("fx-core public index (§4.3)", () => {
  it("exports the verbatim API", async () => {
    const core = await import("./index");
    for (const name of ["fnv1a32", "mulberry32", "hash01", "buildWarp", "toOutput", "toEdit", "warpFromJson",
      "speechSpans", "duckEnvelope", "envelopeDbAt", "mappedCues", "censorText", "censoredWords", "gradeOps",
      "gradeMatrix", "prepareScene", "frameOps", "isPassthrough", "captionHitBoxes", "rasterize", "renderFrame",
      "editStyleToJson", "isFxTemplate"]) {
      expect(typeof (core as Record<string, unknown>)[name], name).toBe("function");
    }
    expect(core.FX_CORE_VERSION).toBe("fx-core-1");
    expect(core.EDIT_FX_VERSION).toBe("fx-v2");
  });
});

describe.skipIf(!indexBuilds)("build-fx-core.mjs", () => {
  const dir = mkdtempSync(join(tmpdir(), "fx-core-build-"));
  afterAll(() => rmSync(dir, { recursive: true, force: true }));
  const build = (name: string) => {
    const out = join(dir, name);
    execFileSync(process.execPath, [join(FRONTEND, "scripts/build-fx-core.mjs"), "--out", out], { cwd: FRONTEND, stdio: "pipe" });
    return readFileSync(out);
  };

  it("is deterministic, banner-stamped ESM with no host imports", () => {
    const a = build("a.js");
    const b = build("b.js");
    expect(a.equals(b)).toBe(true);
    const text = a.toString("utf8");
    expect(text.startsWith("// GENERATED by frontend/scripts/build-fx-core.mjs. Do not edit.\n")).toBe(true);
    expect(text).toMatch(/^export \{/m);
    expect(text).not.toMatch(/^import /m);              // fully bundled: deno loads it with no resolution
    expect(text).not.toContain(FRONTEND);               // no absolute paths: identical on every machine
    expect(text).not.toMatch(/\/\*[!*]|@license|sourceMappingURL/);
  }, 60_000);
});
